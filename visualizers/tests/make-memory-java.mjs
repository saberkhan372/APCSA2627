// Generates MemoryCheck.java from memory-cases.json. Programs run in real Java with the course's
// Player class (projects/W06) and captured output; "compile-error" programs must be rejected by
// javac; "unsupported" programs are valid Java the tool does not model, so javac must accept them.
import { readFileSync, writeFileSync } from 'node:fs';
const cases = JSON.parse(readFileSync(new URL('memory-cases.json', import.meta.url), 'utf8'));
const NAMED = { 8: '\\b', 9: '\\t', 10: '\\n', 12: '\\f', 13: '\\r', 34: '\\"', 92: '\\\\' };
function lit(s) { let o = '"'; for (let i = 0; i < s.length; i++) { const c = s.charCodeAt(i); o += NAMED[c] || (c >= 32 && c <= 126 ? s[i] : c < 32 || c === 127 ? '\\' + c.toString(8).padStart(3, '0') : '\\u' + c.toString(16).padStart(4, '0')); } return o + '"'; }
const indent = (code, n) => code.split('\n').map(l => ' '.repeat(n) + l).join('\n');
const PLAYER = `static class Player {
    private String name;
    private int score;
    public Player(String startName, int startScore) { name = startName; score = startScore; }
    public String getName() { return name; }
    public int getScore() { return score; }
    public void addScore(int amount) { score += amount; }
}`;
const methods = [], runs = [], compiles = [];
cases.forEach(([code, want], i) => {
  if (want === 'compile-error' || want === 'unsupported') {
    compiles.push(`        compileCheck(javac, ${lit(code)}, ${lit(`public class Snip {\n${PLAYER}\nstatic void run() {\n${code}\n}\n}`)}, ${want === 'unsupported'});`);
    return;
  }
  methods.push(`    static void m${i}() {\n${indent(code, 8)}\n    }`);
  runs.push(`        check(${lit(code)}, ${lit(want)}, MemoryCheck::m${i});`);
});
const java = `// Generated by make-memory-java.mjs from memory-cases.json. Do not edit by hand.
import java.io.ByteArrayOutputStream;
import java.io.PrintStream;
import java.net.URI;
import java.nio.file.Files;
import java.util.List;
import javax.tools.DiagnosticCollector;
import javax.tools.JavaCompiler;
import javax.tools.JavaFileObject;
import javax.tools.SimpleJavaFileObject;
import javax.tools.ToolProvider;

public class MemoryCheck {
${indent(PLAYER, 4)}

${methods.join('\n')}

    static int passed = 0, failed = 0;
    static String capture(Runnable r) {
        PrintStream old = System.out;
        ByteArrayOutputStream buf = new ByteArrayOutputStream();
        System.setOut(new PrintStream(buf, true));
        String tail = "";
        try { r.run(); } catch (RuntimeException e) { tail = "|throws:" + e.getClass().getSimpleName(); } finally { System.setOut(old); }
        return buf.toString().replace(System.lineSeparator(), "\\n") + tail;
    }
    static void check(String code, String want, Runnable r) {
        String got = capture(r);
        if (got.equals(want)) passed++;
        else { failed++; System.out.println("FAIL " + show(code) + "\\n  Java  " + show(got) + "\\n  table " + show(want)); }
    }
    static void compileCheck(JavaCompiler javac, String code, String source, boolean shouldCompile) throws Exception {
        JavaFileObject src = new SimpleJavaFileObject(URI.create("string:///Snip.java"), JavaFileObject.Kind.SOURCE) {
            @Override public CharSequence getCharContent(boolean ignore) { return source; }
        };
        String out = Files.createTempDirectory("snip").toString();
        boolean ok = javac.getTask(null, null, new DiagnosticCollector<JavaFileObject>(), List.of("-d", out), null, List.of(src)).call();
        if (ok == shouldCompile) passed++;
        else { failed++; System.out.println("FAIL " + show(code) + ": Java " + (ok ? "compiles" : "rejects") + " it, the table says it " + (shouldCompile ? "is valid Java the tool does not model" : "does not compile")); }
    }
    static String show(String s) { return "\\"" + s.replace("\\n", "\\\\n") + "\\""; }

    public static void main(String[] args) throws Exception {
${runs.join('\n')}
        JavaCompiler javac = ToolProvider.getSystemJavaCompiler();
        if (javac == null) throw new IllegalStateException("A JDK is needed to check compile claims.");
${compiles.join('\n')}
        System.out.println(failed == 0 ? "PASS: " + passed + " programs match Java " + System.getProperty("java.version") : failed + " of " + (passed + failed) + " programs differ");
    }
}
`;
writeFileSync(new URL('MemoryCheck.java', import.meta.url), java);
console.log(`Wrote MemoryCheck.java with ${runs.length} programs and ${compiles.length} compile checks`);
