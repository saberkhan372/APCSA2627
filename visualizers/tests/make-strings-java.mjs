// Generates StringIndexCheck.java: a self-contained program that checks every case in
// strings-cases.json against real Java, including a line-by-line run of the
// WorkingWithStrings lab statements. Run `java StringIndexCheck.java` or paste it into any Java runner.
import { readFileSync, writeFileSync } from 'node:fs';
const here = new URL('.', import.meta.url);
const { calls, lab } = JSON.parse(readFileSync(new URL('strings-cases.json', here), 'utf8'));

// Named or octal escapes for control characters: Java translates \u escapes before
// lexing, so "\u000a" would put a real line break inside the literal.
const NAMED = { 8: '\\b', 9: '\\t', 10: '\\n', 12: '\\f', 13: '\\r', 34: '\\"', 92: '\\\\' };
function lit(s) {
  let out = '"';
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    if (NAMED[c]) out += NAMED[c];
    else if (c >= 32 && c <= 126) out += s[i];
    else if (c < 32 || c === 127) out += '\\' + c.toString(8).padStart(3, '0');
    else out += '\\u' + c.toString(16).padStart(4, '0');
  }
  return out + '"';
}
const callRows = calls.map(([s, m, args, kind, value]) =>
  `        {${lit(s)}, "${m}", ${lit(m === 'indexOf' ? args[0] : args.join(','))}, "${kind}", ${lit(value)}},`).join('\n');
const labRows = lab.map(([name, phrase, expected]) => `        {${lit(name)}, ${lit(phrase)}, ${lit(expected)}},`).join('\n');

const java = `// Generated by make-strings-java.mjs from strings-cases.json. Do not edit by hand.
public class StringIndexCheck {
    // {string, method, argument (indexOf: the target; otherwise comma-separated ints), expected kind, expected value}
    static final String[][] CALLS = {
${callRows}
    };
    // {full name, phrase, expected trace}
    static final String[][] LAB = {
${labRows}
    };

    public static void main(String[] args) {
        int failures = 0;
        for (String[] c : CALLS) {
            String got = call(c[0], c[1], c[2]);
            String want = c[3] + ":" + c[4];
            if (!got.equals(want)) {
                failures++;
                System.out.println("FAIL " + q(c[0]) + "." + c[1] + ": got " + got + ", table says " + want);
            }
        }
        for (String[] c : LAB) {
            String got = lab(c[0], c[1]);
            if (!got.equals(c[2])) {
                failures++;
                System.out.println("FAIL lab " + q(c[0]) + " / " + q(c[1]) + "\\n  got   " + got + "\\n  table " + c[2]);
            }
        }
        int total = CALLS.length + LAB.length;
        System.out.println(failures == 0
            ? "PASS: " + CALLS.length + " calls and " + LAB.length + " lab runs match Java " + System.getProperty("java.version")
            : failures + " of " + total + " cases differ");
    }

    static String call(String s, String m, String arg) {
        String[] a = arg.split(",");
        try {
            switch (m) {
                case "length": return "int:" + s.length();
                case "charAt": return "char:" + s.charAt(Integer.parseInt(a[0]));
                case "substring1": return "String:" + s.substring(Integer.parseInt(a[0]));
                case "substring2": return "String:" + s.substring(Integer.parseInt(a[0]), Integer.parseInt(a[1]));
                case "indexOf": return "int:" + s.indexOf(arg);
                default: throw new IllegalArgumentException(m);
            }
        } catch (StringIndexOutOfBoundsException e) {
            return "throws:";
        }
    }

    // The String statements of WorkingWithStrings.java, in order. line matches the tracer's numbering.
    static String lab(String fullname, String phrase) {
        StringBuilder out = new StringBuilder();
        int line = 0;
        try {
            line = 0; int space = fullname.indexOf(" "); out.append("space=" + space + ";");
            line = 1; String firstName = fullname.substring(0, space); out.append("firstName=" + q(firstName) + ";");
            line = 2; String secondName = fullname.substring(space + 1); out.append("secondName=" + q(secondName) + ";");
            line = 3; fullname = (secondName + " " + firstName); out.append("fullname=" + q(fullname) + ";");
            line = 4; int phraseLength = phrase.length(); out.append("phraseLength=" + phraseLength + ";");
            line = 5; int middleIndex = phraseLength / 2; out.append("middleIndex=" + middleIndex + ";");
            line = 6; String firstHalf = phrase.substring(0, middleIndex); out.append("firstHalf=" + q(firstHalf) + ";");
            line = 7; String secondHalf = phrase.substring(middleIndex, phraseLength); out.append("secondHalf=" + q(secondHalf) + ";");
            line = 8; String switchedPhrase = secondHalf.concat(firstHalf); out.append("switchedPhrase=" + q(switchedPhrase) + ";");
            line = 9; String middle3 = phrase.substring(middleIndex - 1, middleIndex + 2); out.append("middle3=" + q(middle3) + ";");
            line = 10; char middleChar = phrase.charAt(middleIndex); out.append("middleChar=" + q(String.valueOf(middleChar)) + ";");
        } catch (StringIndexOutOfBoundsException e) {
            out.append("THROWS@" + line);
        }
        return out.toString();
    }

    static String q(String s) {
        return "\\"" + s.replace("\\\\", "\\\\\\\\").replace("\\"", "\\\\\\"") + "\\"";
    }
}
`;
writeFileSync(new URL('StringIndexCheck.java', here), java);
console.log(`Wrote StringIndexCheck.java with ${calls.length} calls and ${lab.length} lab runs`);
