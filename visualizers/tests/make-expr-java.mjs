// Generates ExprCheck.java from expr-cases.json. Valid cases are compiled as real Java code:
// overloads typed(int), typed(double) and typed(String) make javac itself confirm each result's
// type. "compile-error" cases are compiled in memory with javax.tools and must be rejected.
// "unsupported" cases are valid Java the tool does not handle: javac must accept them, which
// confirms the tool never reports valid Java as a compile error.
import { readFileSync, writeFileSync } from 'node:fs';
const here = new URL('.', import.meta.url);
const cases = JSON.parse(readFileSync(new URL('expr-cases.json', here), 'utf8'));

const NAMED = { 8: '\\b', 9: '\\t', 10: '\\n', 12: '\\f', 13: '\\r', 34: '\\"', 92: '\\\\' };
function lit(s) {
  let out = '"';
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    if (NAMED[c]) out += NAMED[c];
    else if (c >= 32 && c <= 126) out += s[i];
    else if (c < 32 || c === 127) out += '\\' + c.toString(8).padStart(3, '0');
    else out += '\\u' + c.toString(16).padStart(4, '0');
  }
  return out + '"';
}
// Split declarations on ; or newline outside String literals, as the page does.
function splitDecls(src) {
  const parts = [];
  let cur = '', inStr = false;
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (inStr) { cur += c; if (c === '\\' && i + 1 < src.length) cur += src[++i]; else if (c === '"') inStr = false; continue; }
    if (c === '"') { inStr = true; cur += c; continue; }
    if (c === ';' || c === '\n') { parts.push(cur); cur = ''; continue; }
    cur += c;
  }
  parts.push(cur);
  return parts.map(x => x.trim()).filter(Boolean).map(x => x + ';').join(' ');
}
// The same Java body is used inline and in the compile-error snippets.
function body(decls, stmt) {
  const ds = splitDecls(decls);
  const s = stmt.trim().replace(/;$/, '');
  const m = /^(int|double|String)\s+([A-Za-z_]\w*)\s*=([\s\S]*)$/.exec(s);
  return (ds ? ds + ' ' : '') + (m ? `${m[1]} ${m[2]} =${m[3]}; return typed(${m[2]});` : `return typed(${s});`);
}
const TYPED = 'static String typed(int v) { return "int:" + v; } static String typed(double v) { return "double:" + v; } static String typed(String v) { return "String:" + v; }';

// For unsupported cases: any declared type, and the expression returned as an Object.
// The newline before ")" ends a trailing // comment.
function objectBody(decls, stmt) {
  const ds = splitDecls(decls);
  const s = stmt.trim().replace(/;$/, '');
  const m = /^([A-Za-z_$][\w$.<>\[\]]*)\s+([A-Za-z_$][\w$]*)\s*=(?!=)([\s\S]*)$/.exec(s);
  return (ds ? ds + ' ' : '') + (m ? `${m[1]} ${m[2]} =${m[3]}\n; return ${m[2]};` : `return (${s}\n);`);
}
const valid = cases.filter(c => c[2] !== 'compile-error' && c[2] !== 'unsupported');
const bad = cases.filter(c => c[2] === 'compile-error');
const unsupported = cases.filter(c => c[2] === 'unsupported');
const methods = valid.map((c, i) => `    static String c${i}() { ${body(c[0], c[1])} }`).join('\n');
const table = valid.map((c, i) => `        {${lit(c[0])}, ${lit(c[1])}, ${lit(c[2])}},`).join('\n');
const dispatch = valid.map((c, i) => `            case ${i}: return c${i}();`).join('\n');
const okRows = unsupported.map(c => `        {${lit(c[0])}, ${lit(c[1])}, ${lit(`public class Snip { static Object run() { ${objectBody(c[0], c[1])} } }`)}},`).join('\n');
const badRows = bad.map(c => `        {${lit(c[0])}, ${lit(c[1])}, ${lit(`public class Snip { ${TYPED} static String run() { ${body(c[0], c[1])} } }`)}},`).join('\n');

const java = `// Generated by make-expr-java.mjs from expr-cases.json. Do not edit by hand.
import java.net.URI;
import java.nio.file.Files;
import java.util.List;
import javax.tools.DiagnosticCollector;
import javax.tools.JavaCompiler;
import javax.tools.JavaFileObject;
import javax.tools.SimpleJavaFileObject;
import javax.tools.ToolProvider;

public class ExprCheck {
    ${TYPED}

${methods}

    // {declarations, statement, expected}
    static final String[][] VALID = {
${table}
    };
    // {declarations, statement, source that javac must reject}
    static final String[][] REJECT = {
${badRows}
    };
    // {declarations, statement, source that javac must accept: valid Java the tool marks unsupported}
    static final String[][] ACCEPT = {
${okRows}
    };

    static String run(int i) {
        switch (i) {
${dispatch}
            default: throw new IllegalArgumentException();
        }
    }

    public static void main(String[] args) throws Exception {
        int failures = 0;
        for (int i = 0; i < VALID.length; i++) {
            String got;
            try { got = run(i); } catch (ArithmeticException e) { got = "throws:ArithmeticException"; }
            if (!got.equals(VALID[i][2])) {
                failures++;
                System.out.println("FAIL [" + VALID[i][0] + "] " + VALID[i][1] + ": Java gives " + got + ", table says " + VALID[i][2]);
            }
        }
        JavaCompiler javac = ToolProvider.getSystemJavaCompiler();
        if (javac == null) throw new IllegalStateException("A JDK (not just a JRE) is needed to check compile errors.");
        for (String[] c : REJECT) {
            if (compiles(javac, c[2])) {
                failures++;
                System.out.println("FAIL [" + c[0] + "] " + c[1] + ": Java compiles it, but the table says it does not");
            }
        }
        for (String[] c : ACCEPT) {
            if (!compiles(javac, c[2])) {
                failures++;
                System.out.println("FAIL [" + c[0] + "] " + c[1] + ": the tool calls it unsupported, but it is not valid Java");
            }
        }
        int total = VALID.length + REJECT.length + ACCEPT.length;
        System.out.println(failures == 0
            ? "PASS: " + VALID.length + " results, " + REJECT.length + " compile errors and " + ACCEPT.length + " valid-but-unsupported cases match Java " + System.getProperty("java.version")
            : failures + " of " + total + " cases differ");
    }

    static boolean compiles(JavaCompiler javac, String code) throws Exception {
        JavaFileObject src = new SimpleJavaFileObject(URI.create("string:///Snip.java"), JavaFileObject.Kind.SOURCE) {
            @Override public CharSequence getCharContent(boolean ignoreEncodingErrors) { return code; }
        };
        String out = Files.createTempDirectory("snip").toString();
        return javac.getTask(null, null, new DiagnosticCollector<JavaFileObject>(), List.of("-d", out), null, List.of(src)).call();
    }
}
`;
writeFileSync(new URL('ExprCheck.java', here), java);
console.log(`Wrote ExprCheck.java with ${valid.length} results, ${bad.length} compile errors and ${unsupported.length} valid-but-unsupported cases`);
