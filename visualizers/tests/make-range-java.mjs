// Generates RangeCheck.java: every formula in range-cases.json is evaluated in real Java at both ends of
// Math.random()'s interval and at the midpoints of 12,000 slices, and compared with the table; the
// engine's own values at sample points are compared too.
import { readFileSync, writeFileSync } from 'node:fs';
import { loadPage } from './lib-page.mjs';
const { api } = loadPage('randomrange.html', ['compileFormula', 'evalAt', 'R_TOP']);
const cases = JSON.parse(readFileSync(new URL('range-cases.json', import.meta.url), 'utf8'));
const javaR = src => src.trim().replace(/Math\.random\s*\(\s*\)/g, 'r');
const samples = [0, api.R_TOP, ...Array.from({ length: 64 }, (_, i) => (i + 0.5) / 64)];
const jd = v => v === api.R_TOP ? 'Math.nextDown(1.0)' : (Number.isInteger(v) ? v + '.0' : String(v));
const methods = [], checks = [], rejects = [];
cases.forEach((c, i) => {
  const lit = JSON.stringify(c.f);
  if (c.error === 'compile-error') {
    rejects.push(`        compileCheck(javac, ${lit}, ${JSON.stringify(`public class Snip { static int f(double r) { return ${javaR(c.f)}; } }`)}, false);`);
    return;
  }
  if (c.error === 'unsupported') {
    rejects.push(`        compileCheck(javac, ${lit}, ${JSON.stringify(`public class Snip { static int f() { return ${c.f}; } }`)}, true);`);
    return;
  }
  methods.push(`    static int f${i}(double r) { return ${javaR(c.f)}; }`);
  if (c.error) { checks.push(`        expectThrows(${lit}, ${JSON.stringify(c.error.split(':')[1])}, () -> f${i}(0.5));`); return; }
  const f = api.compileFormula(c.f);
  const engineVals = samples.map(r => api.evalAt(f, r).value);
  if (c.tooMany) { checks.push(`        ends(${lit}, OutputFn.of(RangeCheck::f${i}), ${c.min}, ${c.max}, new int[] {${engineVals.join(', ')}});`); return; }
  checks.push(`        analyze(${lit}, OutputFn.of(RangeCheck::f${i}), ${c.min}, ${c.max}, ${c.count}, ${c.mode === null ? 'null' : c.mode}, "${c.edgeLow.join(',')}", "${c.edgeTop.join(',')}", new int[] {${engineVals.join(', ')}});`);
});
const java = `// Generated by make-range-java.mjs from range-cases.json. Do not edit by hand.
import java.net.URI;
import java.nio.file.Files;
import java.util.List;
import java.util.TreeMap;
import javax.tools.DiagnosticCollector;
import javax.tools.JavaCompiler;
import javax.tools.JavaFileObject;
import javax.tools.SimpleJavaFileObject;
import javax.tools.ToolProvider;

public class RangeCheck {
${methods.join('\n')}

    interface OutputFn { int apply(double r); static OutputFn of(OutputFn f) { return f; } }
    static final int GRID = 12000;
    static final double[] SAMPLES = { ${samples.map(jd).join(', ')} };
    static int passed = 0, failed = 0;

    static void fail(String formula, String what) { failed++; System.out.println("FAIL " + formula + ": " + what); }

    static void analyze(String formula, OutputFn f, int min, int max, int count, Integer mode, String edgeLow, String edgeTop, int[] engine) {
        TreeMap<Integer, Integer> counts = new TreeMap<>();
        for (int i = 0; i < GRID; i++) counts.merge(f.apply((i + 0.5) / GRID), 1, Integer::sum);
        int lo = f.apply(0.0), hi = f.apply(Math.nextDown(1.0));
        TreeMap<Integer, Integer> all = new TreeMap<>(counts);
        all.putIfAbsent(lo, 0); all.putIfAbsent(hi, 0);
        String low = counts.containsKey(lo) ? "" : String.valueOf(lo);
        String top = counts.containsKey(hi) || hi == lo ? "" : String.valueOf(hi);
        Integer best = null; int bestCount = -1; boolean tie = false;
        for (var e : counts.entrySet()) { if (e.getValue() > bestCount) { bestCount = e.getValue(); best = e.getKey(); tie = false; } else if (e.getValue() == bestCount) tie = true; }
        if (tie) best = null;
        String got = all.firstKey() + " " + all.lastKey() + " " + all.size() + " " + best + " [" + low + "] [" + top + "]";
        String want = min + " " + max + " " + count + " " + mode + " [" + edgeLow + "] [" + edgeTop + "]";
        if (!got.equals(want)) fail(formula, "Java gives min max count mode edges = " + got + ", table says " + want);
        for (int s = 0; s < SAMPLES.length; s++)
            if (f.apply(SAMPLES[s]) != engine[s]) fail(formula, "at r = " + SAMPLES[s] + " Java gives " + f.apply(SAMPLES[s]) + ", the page's engine gives " + engine[s]);
        passed++;
    }
    // Formulas with too many values: only the two ends are claimed (the formula rises steadily).
    static void ends(String formula, OutputFn f, int min, int max, int[] engine) {
        int lo = f.apply(0.0), hi = f.apply(Math.nextDown(1.0));
        if (lo != min || hi != max) fail(formula, "Java gives " + lo + " to " + hi + ", table says " + min + " to " + max);
        for (int s = 0; s < SAMPLES.length; s++)
            if (f.apply(SAMPLES[s]) != engine[s]) fail(formula, "at r = " + SAMPLES[s] + " Java gives " + f.apply(SAMPLES[s]) + ", the page's engine gives " + engine[s]);
        passed++;
    }
    static void expectThrows(String formula, String type, Runnable r) {
        try { r.run(); fail(formula, "Java does not throw"); } catch (RuntimeException e) { if (e.getClass().getSimpleName().equals(type)) passed++; else fail(formula, "Java throws " + e.getClass().getSimpleName()); }
    }
    static void expectThrows(String formula, String type, java.util.function.IntSupplier s) { expectThrows(formula, type, (Runnable) () -> s.getAsInt()); }
    static void compileCheck(JavaCompiler javac, String formula, String source, boolean shouldCompile) throws Exception {
        JavaFileObject src = new SimpleJavaFileObject(URI.create("string:///Snip.java"), JavaFileObject.Kind.SOURCE) {
            @Override public CharSequence getCharContent(boolean ignore) { return source; }
        };
        String out = Files.createTempDirectory("snip").toString();
        if (javac.getTask(null, null, new DiagnosticCollector<JavaFileObject>(), List.of("-d", out), null, List.of(src)).call() == shouldCompile) passed++;
        else fail(formula, "Java " + (shouldCompile ? "rejects a valid formula" : "compiles an invalid formula"));
    }

    public static void main(String[] args) throws Exception {
${checks.join('\n')}
        JavaCompiler javac = ToolProvider.getSystemJavaCompiler();
        if (javac == null) throw new IllegalStateException("A JDK is needed to check compile errors.");
${rejects.join('\n')}
        System.out.println(failed == 0 ? "PASS: " + passed + " formulas match Java " + System.getProperty("java.version") : failed + " problem(s) in " + (passed + failed) + " checks");
    }
}
`;
writeFileSync(new URL('RangeCheck.java', import.meta.url), java);
console.log(`Wrote RangeCheck.java with ${checks.length} formulas and ${rejects.length} compilation checks`);
