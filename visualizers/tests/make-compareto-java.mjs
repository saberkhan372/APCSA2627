// Generates CompareToCheck.java: a self-contained program (no file reading) that
// checks every case in compareto-cases.json against real Java. Run `java CompareToCheck.java`
// in this folder. Online runners that require a class named Main need the class renamed.
import { readFileSync, writeFileSync } from 'node:fs';
const here = new URL('.', import.meta.url);
const cases = JSON.parse(readFileSync(new URL('compareto-cases.json', here), 'utf8'));

// Java string literal, one escape per UTF-16 code unit (how Java stores Strings).
// Control characters use named or octal escapes, never \uXXXX: Java translates
// \u escapes before lexing, so "\u000a" would put a real line break in the literal.
const NAMED = { 8: '\\b', 9: '\\t', 10: '\\n', 12: '\\f', 13: '\\r', 34: '\\"', 92: '\\\\' };
function lit(s) {
  let out = '"';
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    if (NAMED[c]) out += NAMED[c];
    else if (c >= 32 && c <= 126) out += s[i];
    else if (c < 32 || c === 127) out += '\\' + c.toString(8).padStart(3, '0');
    else out += '\\u' + c.toString(16).padStart(4, '0');
  }
  return out + '"';
}

const rows = cases.map(([a, b, v]) => `        {${lit(a)}, ${lit(b)}, "${v}"},`).join('\n');
const java = `// Generated by make-compareto-java.mjs from compareto-cases.json. Do not edit by hand.
public class CompareToCheck {
    static final String[][] CASES = {
${rows}
    };

    public static void main(String[] args) {
        int failures = 0;
        for (String[] c : CASES) {
            int expected = Integer.parseInt(c[2]);
            int actual = c[0].compareTo(c[1]);
            if (actual != expected) {
                failures++;
                System.out.println("FAIL " + show(c[0]) + ".compareTo(" + show(c[1]) + ") = " + actual + ", table says " + expected);
            }
        }
        System.out.println(failures == 0
            ? "PASS: " + CASES.length + " cases match Java " + System.getProperty("java.version")
            : failures + " of " + CASES.length + " cases differ");
    }

    static String show(String s) {
        StringBuilder sb = new StringBuilder("\\"");
        for (char ch : s.toCharArray()) {
            if (ch >= 32 && ch <= 126) sb.append(ch);
            else sb.append(String.format("\\\\u%04x", (int) ch));
        }
        return sb.append('"').toString();
    }
}
`;
writeFileSync(new URL('CompareToCheck.java', here), java);
console.log(`Wrote CompareToCheck.java with ${cases.length} cases`);
