public class PlusPractice {
    public static void main(String[] args) {
        int a = 7;
        int b = 2;
        System.out.println("Total: " + a + b);
        System.out.println("Total: " + (a + b));
        System.out.println(a + b + " total");
        System.out.println(a / b);
        System.out.println((double) a / b);
        System.out.println((double) (a / b));
    }
}
